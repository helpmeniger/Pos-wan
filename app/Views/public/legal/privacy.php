<h2>1. Données collectées</h2>
<p>Identité (nom, prénom), téléphone, e-mail facultatif, ville et quartier, date de naissance pour les prestataires, informations de profil professionnel,
messages échangés sur la plateforme, historique des missions et des paiements, données techniques de connexion (adresse IP, navigateur) à des fins de sécurité.</p>
<h2>2. Finalités</h2>
<p>Création et sécurité des comptes, mise en relation, suivi des missions et des paiements, prévention de la fraude, traitement des litiges et respect des
obligations légales. Aucune donnée n'est vendue à des tiers.</p>
<h2>3. Documents d'identité</h2>
<p>Ils ne sont demandés que lorsque la mission l'exige, sont stockés hors de tout accès public, consultés uniquement par le personnel habilité (accès journalisé)
et supprimés après le délai de conservation prévu (90 jours après la décision par défaut). Ils ne sont jamais affichés sur un profil.</p>
<h2>4. Localisation</h2>
<p>La position précise n'est utilisée qu'avec votre accord. Avant l'attribution d'une mission, seule une zone approximative (quartier) est affichée.</p>
<h2>5. Messagerie</h2>
<p>Les conversations ne sont lues par le personnel que si elles font l'objet d'un signalement ou d'un litige. Aucune surveillance non annoncée n'est pratiquée.</p>
<h2>6. Vos droits</h2>
<p>Vous pouvez demander l'accès, la rectification ou la suppression de vos données (sous réserve des obligations de conservation, notamment financières)
via la page Contact. Les traitements doivent respecter la réglementation nigérienne relative à la protection des données personnelles.</p>
