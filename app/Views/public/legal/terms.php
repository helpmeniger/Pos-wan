<h2>1. Objet</h2>
<p>JOB NIGER est une plateforme de mise en relation entre des demandeurs de services (particuliers, entreprises, organisations) et des prestataires.
JOB NIGER n'est ni l'employeur des prestataires, ni partie au contrat de prestation conclu entre les utilisateurs.</p>
<h2>2. Comptes</h2>
<p>L'inscription est réservée aux personnes d'au moins 16 ans ; certaines missions exigent un âge supérieur. Les informations fournies doivent être exactes.
Chaque utilisateur est responsable de la confidentialité de son mot de passe.</p>
<h2>3. Missions</h2>
<p>Les annonces doivent décrire une activité licite, préciser la rémunération, les horaires, le lieu et les conditions. Sont interdits : les frais de candidature
ou de recrutement, les fausses offres, les activités illégales, et l'exercice d'une profession réglementée sans autorisation.</p>
<p>Les missions présentant des risques (travail en hauteur, électricité, conduite professionnelle, travail auprès de mineurs ou de personnes vulnérables…)
sont réservées aux prestataires disposant des vérifications et qualifications requises.</p>
<h2>4. Prestation indépendante et droit du travail</h2>
<p>Les missions sont par défaut des prestations de services indépendantes. Lorsqu'une relation présente les caractéristiques d'un contrat de travail,
le donneur d'ordre reste tenu de respecter le Code du travail et ses obligations déclaratives. La plateforme ne peut servir à contourner ces obligations.</p>
<h2>5. Commissions et paiements</h2>
<p>JOB NIGER perçoit une commission sur les prestations suivies sur la plateforme. Son montant, la partie qui la supporte, le total payé par le demandeur
et le montant net du prestataire sont affichés avant l'acceptation du récapitulatif de mission. Tant qu'aucun prestataire de paiement habilité n'est intégré,
les paiements sont effectués directement entre utilisateurs et la plateforme ne détient pas les fonds.</p>
<h2>6. Litiges</h2>
<p>En cas de désaccord, JOB NIGER propose une médiation fondée sur les éléments du dossier (récapitulatif, messages, preuves). La plateforme n'est pas une juridiction :
les utilisateurs conservent la possibilité de saisir les juridictions compétentes au Niger.</p>
<h2>7. Sanctions et recours</h2>
<p>Un compte peut être suspendu ou fermé en cas de fraude, d'abus ou de non-respect des présentes conditions. La décision est motivée et l'utilisateur peut
la contester auprès du support.</p>
